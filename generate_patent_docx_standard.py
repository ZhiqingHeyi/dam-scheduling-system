def setup_section(sec):
    sec.page_width = Mm(210)
    sec.page_height = Mm(297)
    sec.left_margin = Mm(25)
    sec.top_margin = Mm(25)
    sec.right_margin = Mm(15)
    sec.bottom_margin = Mm(15)
    footer = sec.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r1 = p.add_run()
    f1 = OxmlElement('w:fldChar')
    f1.set(qn('w:fldCharType'), 'begin')
    r1._r.append(f1)
    r2 = p.add_run()
    ins = OxmlElement('w:instrText')
    ins.set(qn('xml:space'), 'preserve')
    ins.text = ' PAGE '
    r2._r.append(ins)
    r3 = p.add_run()
    f2 = OxmlElement('w:fldChar')
    f2.set(qn('w:fldCharType'), 'end')
    r3._r.append(f2)
    sectPr = sec._sectPr
    pgNum = OxmlElement('w:pgNumType')
    pgNum.set(qn('w:start'), '1')
    sectPr.append(pgNum)


setup_section(doc.sections[0])

_cnt = [0]


def _n():
    _cnt[0] += 1
    return "[{:04d}]".format(_cnt[0])


def _run(p, text, fn='SimSun', fs=12, bold=False, italic=False):
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.size = Pt(fs)
    r.font.name = fn
    r.element.rPr.rFonts.set(qn('w:eastAsia'), fn)
    return r


def add_num(text, indent=True, bold=False):
    num = _n()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    _run(p, num + " ")
    _run(p, text, bold=bold)
    return p


def add_heading_num(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(6)
    num = _n()
    _run(p, num + " ")
    _run(p, text, bold=True)
    return p


def add_formula_num(text):
    num = _n()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(6)
    _run(p, num + " ")
    r = p.add_run(text)
    r.font.size = Pt(12)
    r.font.name = 'Times New Roman'
    r.italic = True
    return p


def add_center(text, fs=16, bold=True):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(12)
    p.paragraph_format.space_before = Pt(6)
    _run(p, text, fs=fs, bold=bold)
    return p


def add_claim(num, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Pt(24)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(6)
    _run(p, "{}. ".format(num), bold=True)
    _run(p, text)
    return p


def add_fig(img_num, label, w=5.5):
    img_path = os.path.join(FIG_DIR, "fig{}.png".format(img_num))
    if os.path.exists(img_path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(4)
        r = p.add_run()
        r.add_picture(img_path, width=Inches(w))
    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p2.paragraph_format.space_after = Pt(12)
    _run(p2, label, fs=10)
    return p2


